type QuizQuestion = readonly [string, readonly string[], number];
type PreparedQuestion = [string, string[], number];
function mixQuestion(question: QuizQuestion): PreparedQuestion {
  const variants = question[1].map((text, index) => ({
    text,
    correct: index === question[2],
  }));
  for (let i = variants.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [variants[i], variants[j]] = [variants[j], variants[i]];
  }
  return [
    question[0],
    variants.map((v) => v.text),
    variants.findIndex((v) => v.correct),
  ];
}

